#!/usr/bin/env bash
# Regenerate the workflow screenshots (proposal 50) and their index.
# Headless: Flutter widget tests with golden files, no emulator or browser.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/docs/screenshots"

cd "$root/app"
"${FLUTTER:-flutter}" test screenshots --update-goldens

# Index: one heading per workflow, one sub-heading per size, one image per step.
title() { local t="${1//-/ }"; echo "$(tr '[:lower:]' '[:upper:]' <<<"${t:0:1}")${t:1}"; }
{
  echo "# Workflow screenshots"
  echo
  echo "Generated by \`scripts/screenshots.sh\` (proposal 50). Do not edit by hand."
  for wf in "$out"/*/; do
    [ -d "$wf" ] || continue
    name="$(basename "$wf")"
    echo
    echo "## $(title "$name")"
    for size in phone desktop desktop-compact; do
      [ -d "$wf$size" ] || continue
      echo
      echo "### $size"
      echo
      for img in "$wf$size"/*.png; do
        f="$(basename "$img" .png)"
        echo "![${f#*-}]($name/$size/$f.png)"
        echo
        echo "*${f%%-*}. $(title "${f#*-}")*"
        echo
      done
    done
  done
} > "$out/README.md"
echo "Wrote $out/README.md"
